import { readFile, writeFile } from 'node:fs/promises';
import { join } from 'node:path';
import vm from 'node:vm';

const modules = process.env.YNAMP_PATH || join(process.env.LOCALAPPDATA,
  'Firaxis Games', "Sid Meier's Civilization VII", 'Mods', 'ynamp', 'modules');
const target = new URL('../anthroprocenia/data/civilizations-giant-earth.sql', import.meta.url);
const original = await readFile(target, 'utf8');
const marker = '\n-- Nearby alternatives generated by tools/build-giant-earth-starts.mjs.';
const primarySql = original.split(marker)[0].trimEnd();
const context = vm.createContext({ console: { log() {} } });
vm.runInContext((await readFile(join(modules, 'maps', 'giant-earth-map', 'giant-earth-data.js'), 'utf8'))
  .replace(/^export /gm, ''), context);
const terrain = context.GetMap();
const distance = (a, b) => {
  const q = a[0] - (a[1] - (a[1] & 1)) / 2 - b[0] + (b[1] - (b[1] & 1)) / 2;
  const r = a[1] - b[1];
  return Math.max(Math.abs(q), Math.abs(r), Math.abs(q + r));
};
const rows = [];
for (const [, civ, xText, yText] of primarySql.matchAll(/\('GiantEarth', '(CIVILIZATION_ANTHRO_\w+)',\s*(\d+),\s*(\d+)\)/g)) {
  const primary = [Number(xText), Number(yText)], candidates = [];
  for (let x = primary[0] - 4; x <= primary[0] + 4; x++) {
    for (let y = primary[1] - 4; y <= primary[1] + 4; y++) {
      const tile = terrain[x]?.[y], d = distance(primary, [x, y]);
      if (d >= 2 && d <= 4 && tile && !/COAST|OCEAN|MOUNTAIN|SNOW|TUNDRA/.test(tile[0]) &&
          tile[2] === terrain[primary[0]][primary[1]][2]) candidates.push([x, y]);
    }
  }
  candidates.sort((a, b) => distance(primary, a) - distance(primary, b) || a[0] - b[0] || a[1] - b[1]);
  let best = [], bestCost;
  for (let count = 4; count >= 0; count--) {
    bestCost = Infinity;
    const search = (chosen, remaining, cost) => {
      const needed = count - chosen.length;
      if (!needed) {
        if (cost < bestCost) { best = chosen; bestCost = cost; }
        return;
      }
      if (remaining.length < needed ||
          cost + remaining.slice(0, needed).reduce((sum, point) => sum + distance(primary, point), 0) >= bestCost) return;
      for (let i = 0; i <= remaining.length - needed; i++) {
        const point = remaining[i];
        search([...chosen, point], remaining.slice(i + 1).filter(other => {
          const d = distance(point, other);
          return d >= 2 && d <= 4;
        }), cost + distance(primary, point));
      }
    };
    search([], candidates, 0);
    if (bestCost < Infinity) break;
  }
  for (const [x, y] of best) rows.push(`  ('GiantEarth', '${civ}', ${x}, ${y}, 1)`);
  console.log(`${civ}: ${best.length + 1} starts`);
}
if (!rows.length) throw new Error('No primary civilization starts found.');
await writeFile(target, `${primarySql}\n${marker}\n` +
  '-- Preserve the primary homeland; all pairs are 2-4 hex tiles apart on existing land.\n' +
  '-- Small islands retain fewer candidates rather than adding land or moving abroad.\n' +
  'INSERT INTO StartPosition (MapName, Civilization, X, Y, AlternateStart) VALUES\n' +
  `${rows.join(',\n')};\n`);
